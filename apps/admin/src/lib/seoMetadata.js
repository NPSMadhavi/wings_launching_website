/**
 * Helper to get metadata by path.
 */
export function getSeoMetadata(path) {
  if (!path) return null;
  const clean = path.startsWith("/") ? path : `/${path}`;
  // Strip trailing slash unless it's just "/"
  const normalized = clean.length > 1 ? clean.replace(/\/+$/, "") : clean;
  return (
    SEO_METADATA_MAP[normalized] ||
    SEO_METADATA_MAP[normalized.toLowerCase()] ||
    null
  );
}
